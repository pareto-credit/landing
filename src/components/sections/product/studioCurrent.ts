import vertexSource from "./studio-current.vert.glsl?raw";
import fragmentSource from "./studio-current.frag.glsl?raw";

export function createStudioCurrent(canvas: HTMLCanvasElement) {
  if (typeof WebGL2RenderingContext === "undefined") return null;
  const context = canvas.getContext("webgl2", {
    alpha: false, antialias: false, depth: false, stencil: false, powerPreference: "low-power",
  });
  if (!context) return null;
  const gl = context;

  const program = gl.createProgram();
  if (!program) return null;
  for (const [type, source] of [[gl.VERTEX_SHADER, vertexSource], [gl.FRAGMENT_SHADER, fragmentSource]] as const) {
    const shader = gl.createShader(type);
    if (!shader) {
      gl.deleteProgram(program);
      return null;
    }
    gl.shaderSource(shader, source);
    gl.compileShader(shader);
    gl.attachShader(program, shader);
    gl.deleteShader(shader);
  }
  gl.linkProgram(program);
  if (!gl.getProgramParameter(program, gl.LINK_STATUS)) {
    gl.deleteProgram(program);
    return null;
  }

  const cover = gl.getUniformLocation(program, "coverScale");
  const anchor = gl.getUniformLocation(program, "anchorX");
  const artWidth = gl.getUniformLocation(program, "artWidthCss");
  const pixelRatio = gl.getUniformLocation(program, "deviceScale");
  const phase = gl.getUniformLocation(program, "phase");
  const layer = gl.getUniformLocation(program, "layer");
  const [maxWidth, maxHeight] = gl.getParameter(gl.MAX_VIEWPORT_DIMS) as Int32Array;
  const maxBuffer = gl.getParameter(gl.MAX_RENDERBUFFER_SIZE) as number;
  const mobile = window.matchMedia("(max-width: 767px)");
  let running = false;
  let frame = 0;
  let elapsed = 0;
  let previous: number | undefined;
  let lastDraw = -Infinity;

  gl.useProgram(program);
  gl.enable(gl.BLEND);
  gl.blendFunc(gl.SRC_ALPHA, gl.ONE_MINUS_SRC_ALPHA);

  function draw() {
    // The grid is generated by vertex ID. Only its phase changes between frames.
    gl.uniform1f(phase, (elapsed % 16_000) / 16_000);
    gl.uniform1i(layer, 0);
    gl.drawArrays(gl.TRIANGLES, 0, 3);
    gl.uniform1i(layer, 1);
    gl.drawArrays(gl.TRIANGLES, 0, 12 * 64 * 24 * 6);
  }

  function resize() {
    const { width, height } = canvas.getBoundingClientRect();
    if (!width || !height) return;
    const density = Math.min(window.devicePixelRatio || 1, Math.min(maxWidth, maxBuffer) / width, Math.min(maxHeight, maxBuffer) / height);
    const w = Math.max(1, Math.round(width * density));
    const h = Math.max(1, Math.round(height * density));
    if (canvas.width !== w || canvas.height !== h) {
      canvas.width = w;
      canvas.height = h;
    }
    const bw = gl.drawingBufferWidth;
    const bh = gl.drawingBufferHeight;
    if (!bw || !bh) return;
    const scale = Math.max(bw / 1440, bh / 960);
    gl.viewport(0, 0, bw, bh);
    gl.uniform2f(cover, 1440 * scale / bw, 960 * scale / bh);
    gl.uniform1f(anchor, mobile.matches ? 0.57 : 0.60);
    const displayDensity = bw / width;
    gl.uniform1f(artWidth, 1440 * scale / displayDensity);
    gl.uniform1f(pixelRatio, displayDensity);
    draw();
  }

  function tick(now: number) {
    if (previous !== undefined) elapsed += now - previous;
    previous = now;
    if (now - lastDraw >= 1000 / 30 - 0.5) {
      draw();
      lastDraw = now;
    }
    frame = requestAnimationFrame(tick);
  }

  const observer = new ResizeObserver(resize);
  observer.observe(canvas);
  // Moving a paused window between monitors can change density without changing its CSS size.
  let resolution = window.matchMedia(`(resolution: ${window.devicePixelRatio}dppx)`);
  function monitorChanged() {
    resolution.removeEventListener("change", monitorChanged);
    resolution = window.matchMedia(`(resolution: ${window.devicePixelRatio}dppx)`);
    resolution.addEventListener("change", monitorChanged);
    resize();
  }
  resolution.addEventListener("change", monitorChanged);
  mobile.addEventListener("change", resize);
  resize();

  return {
    setRunning(next: boolean) {
      if (running === next) return;
      running = next;
      previous = undefined;
      if (next) frame = requestAnimationFrame(tick);
      else cancelAnimationFrame(frame);
    },
    dispose() {
      cancelAnimationFrame(frame);
      observer.disconnect();
      resolution.removeEventListener("change", monitorChanged);
      mobile.removeEventListener("change", resize);
      gl.deleteProgram(program);
    },
  };
}
